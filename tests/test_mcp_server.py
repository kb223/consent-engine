def test_read_audit_result_returns_error_text_on_bad_id() -> None:
    from consent_engine.mcp_server import read_audit_result

    result = read_audit_result("../../../etc")
    assert "error" in result.lower()


def test_query_evidence_returns_error_text_on_bad_id() -> None:
    from consent_engine.mcp_server import query_evidence

    result = query_evidence("../etc")
    assert "error" in result.lower()


@pytest.mark.asyncio
async def test_call_tool_surfaces_bad_id_as_text_not_protocol_error() -> None:
    """Bad audit_id is a normal result the model can read, not an isError response.

    Preserved deliberately across the FastMCP migration: raising here would make
    the host render a protocol error instead of letting Claude retry with a
    corrected id.
    """
    from consent_engine.mcp_server import mcp

    result = await mcp.call_tool("read_audit_result", {"audit_id": "../../../etc"})
    blocks, _structured = result
    assert "error" in blocks[0].text.lower()
