@pytest.mark.asyncio
async def test_list_tools_returns_three_audit_tools() -> None:
    """audit_url + read_audit_result + query_evidence."""
    from consent_engine.mcp_server import mcp

    tools = await mcp.list_tools()
    names = {t.name for t in tools}
    assert names == {"audit_url", "read_audit_result", "query_evidence"}


@pytest.mark.asyncio
async def test_tool_schemas_have_required_fields() -> None:
    from consent_engine.mcp_server import mcp

    by_name = {t.name: t for t in await mcp.list_tools()}

    assert by_name["audit_url"].inputSchema["required"] == ["url"]
    assert by_name["read_audit_result"].inputSchema["required"] == ["audit_id"]
    # The three filter params carry defaults, so only audit_id is required.
    assert by_name["query_evidence"].inputSchema["required"] == ["audit_id"]


@pytest.mark.asyncio
async def test_query_evidence_schema_exposes_filter_params() -> None:
    """The optional filters must survive schema generation, not just audit_id."""
    from consent_engine.mcp_server import mcp

    by_name = {t.name: t for t in await mcp.list_tools()}
    props = by_name["query_evidence"].inputSchema["properties"]
    assert set(props) == {"audit_id", "url_contains", "host_contains", "max_results"}
    assert props["max_results"]["default"] == 20


@pytest.mark.asyncio
async def test_tools_carry_descriptions() -> None:
    """FastMCP sources tool descriptions from docstrings; an empty one is a silent regression."""
    from consent_engine.mcp_server import mcp

    for tool in await mcp.list_tools():
        assert tool.description, f"{tool.name} has no description"


# ----------------------------------------------------------------------
# Read-tools handle bad audit_id without raising (return error text)
